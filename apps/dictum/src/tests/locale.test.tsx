import { act } from 'react'
import { afterEach, describe, expect, it } from 'vitest'
import { setLocale } from '@essentia/ui'
import { createDoc, displayTitle, fileName, formatDate } from '../domain/documents'
import { $, buttonNamed, click, contentField, renderApp, rowTitles, savedDocs, setupApp, titleField, type } from './testing'

describe('Dictum locale', () => {
  setupApp()
  afterEach(() => { document.documentElement.lang = 'en-GB' })

  it('creates, versions, deletes and restores a document in Portuguese, preserving its text', () => {
    setLocale('pt-PT')
    const app = renderApp()
    expect(app.textContent).toContain('Ainda não escreveu nada.')
    click(buttonNamed('Novo documento'))
    expect(rowTitles()).toEqual(['Sem título'])
    expect(savedDocs()[0].title).toBe('')
    type(titleField(), 'Original title')
    type(contentField(), '# Original text')
    expect(app.textContent).toContain('2 palavras')
    click(buttonNamed('Versões'))
    expect(app.textContent).toContain('Ainda não há versões.')
    click(buttonNamed('Guardar esta versão'))
    expect(buttonNamed('Esta versão está guardada').disabled).toBe(true)
    click(buttonNamed('Fechar'))
    click(buttonNamed('Eliminar'))
    expect(app.textContent).toContain('“Original title” e as respetivas versões foram eliminados.')
    click(buttonNamed('Anular'))
    expect(savedDocs()[0]).toMatchObject({ title: 'Original title', content: '# Original text' })
    click(buttonNamed('Versões'))
    expect($('.version__excerpt').textContent).toBe('Original text')
  })

  it('preserves the current editor, selection and field drafts through a live locale change', () => {
    renderApp()
    click(buttonNamed('New document'))
    type(titleField(), 'My title')
    type(contentField(), 'Unchanged markdown')
    const tags = $<HTMLInputElement>('.doc-fields__field--wide input')
    type(tags, 'draft tags')
    const editor = contentField()
    editor.focus()
    editor.setSelectionRange(2, 8)
    const saved = savedDocs()
    act(() => { setLocale('pt-PT') })
    expect(contentField()).toBe(editor)
    expect(document.activeElement).toBe(editor)
    expect([editor.selectionStart, editor.selectionEnd]).toEqual([2, 8])
    expect(editor.value).toBe('Unchanged markdown')
    expect(tags.value).toBe('draft tags')
    expect(titleField().value).toBe('My title')
    expect(savedDocs()).toEqual(saved)
    expect(buttonNamed('Pré-visualização')).toBeTruthy()
    expect(buttonNamed('Negrito').title).toContain('Negrito')
  })

  it('retranslates an open versions dialog and deletion notice without losing the document', () => {
    const app = renderApp()
    click(buttonNamed('New document'))
    type(titleField(), 'Keep title')
    click(buttonNamed('Versions'))
    const dialog = $('dialog')
    act(() => { setLocale('pt-PT') })
    expect($('dialog')).toBe(dialog)
    expect(app.textContent).toContain('Ainda não há versões.')
    click(buttonNamed('Fechar'))
    click(buttonNamed('Eliminar'))
    act(() => { setLocale('en-GB') })
    expect(app.textContent).toContain('Deleted “Keep title” and its versions.')
    click(buttonNamed('Undo'))
    expect(titleField().value).toBe('Keep title')
  })

  it('localizes blank-title display and dates while keeping export names and stored content compatible', () => {
    const doc = createDoc('', new Date('2022-10-07T12:00:00Z'), 'stable')
    setLocale('pt-PT')
    expect(displayTitle(doc)).toBe('Sem título')
    expect(fileName(doc)).toBe('Untitled.md')
    expect(fileName({ ...doc, title: 'Plan: v2?' })).toBe('Plan v2.md')
    expect(doc).toMatchObject({ id: 'stable', title: '', content: '', updatedAt: '2022-10-07T12:00:00.000Z' })
    expect(formatDate(doc.updatedAt)).toBe('7/10/2022')
    setLocale('en-GB')
    expect(formatDate(doc.updatedAt)).toBe('7 Oct 2022')
  })
})
